import pytest
from slidextract.formatter import number

expected_results = {
    # Basic integer formatting
    ("0", 0): "0",
    ("0", -123): "-123",
    ("0", 123): "123",
    ("0", 123.45): "123",
    ("0", 123456): "123456",
    ("0", 0.0000123): "0",
    # Decimal formatting (fixed decimal places)
    ("0.00", 0): "0.00",
    ("0.00", -123): "-123.00",
    ("0.00", 123): "123.00",
    ("0.00", 123.45): "123.45",
    ("0.00", 123456): "123456.00",
    ("0.00", 0.0000123): "0.00",
    # Thousand separators
    ("#,##0", 0): "0",
    ("#,##0", -123): "-123",
    ("#,##0", 123): "123",
    ("#,##0", 123.45): "123",
    ("#,##0", 123456): "123,456",
    ("#,##0", 0.0000123): "0",
    ("#,##0.00", 0): "0.00",
    ("#,##0.00", -123): "-123.00",
    ("#,##0.00", 123): "123.00",
    ("#,##0.00", 123.45): "123.45",
    ("#,##0.00", 123456): "123,456.00",
    ("#,##0.00", 0.0000123): "0.00",
    # Negative value formatting
    ("#,##0;-#,##0", 123): "123",
    ("#,##0;-#,##0", -123): "-123",
    ("#,##0.00;-#,##0.00", 123.45): "123.45",
    ("#,##0.00;-#,##0.00", -123.45): "-123.45",
    # Conditional negative color formatting
    ("#,##0;[빨강]-#,##0", 123): "123",
    ("#,##0;[빨강]-#,##0", -123): "-123",
    ("#,##0.00;[빨강]-#,##0.00", 123.45): "123.45",
    ("#,##0.00;[빨강]-#,##0.00", -123.45): "-123.45",
    # Currency formatting (₩)
    ("₩#,##0", 123456): "₩123,456",
    ("₩#,##0;-₩#,##0", -123456): "-₩123,456",
    ("₩#,##0.00", 123456): "₩123,456.00",
    ("₩#,##0.00;-₩#,##0.00", -123456.78): "-₩123,456.78",
    ("₩#,##0;[빨강]-₩#,##0", 123456): "₩123,456",
    ("₩#,##0;[빨강]-₩#,##0", -123456): "-₩123,456",
    # Percentage formatting
    ("0%", 0.5): "50%",
    ("0%", 1): "100%",
    ("0%", 0.123): "12%",
    ("0.00%", 0.123): "12.30%",
    ("0.00%", 1.2345): "123.45%",
    # Scientific notation
    ("0.00E+00", 123456): "1.23E+05",
    ("0.00E+00", 0.0000123): "1.23E-05",
    ("##0.0E+0", 123456): "123.5E+3",
    ("##0.0E+0", 0.0000123): "12.3E-6",
    # Fraction formatting
    ("# ?/?", 0.5): "1/2",
    ("# ?/?", 0.25): "1/4",
    ("# ??/??", 0.3333): "1/3",
    ("# ??/??", 0.6667): "2/3",
    # Text formatting
    ("@", "Hello"): "Hello",
    ('"000"#', 123): "000123",
    # Custom formats with spaces
    ('_-₩* #,##0_-;-₩* #,##0_-;_-₩* "-"_-;_-@_-', 123456): " ₩123,456 ",
    ('_-₩* #,##0_-;-₩* #,##0_-;_-₩* "-"_-;_-@_-', -123456): "-₩123,456 ",
    ('_-₩* #,##0.00_-;-₩* #,##0.00_-;_-₩* "-"??_-;_-@_-', 123456.78): " ₩123,456.78 ",
    ('_-₩* #,##0.00_-;-₩* #,##0.00_-;_-₩* "-"??_-;_-@_-', -123456.78): "-₩123,456.78 ",
    # Accounting formats
    ("$#,##0_);($#,##0)", 123456): "$123,456 ",
    ("$#,##0_);($#,##0)", -123456): "($123,456)",
    ("$#,##0.00_);($#,##0.00)", 123456.78): "$123,456.78 ",
    ("$#,##0.00_);($#,##0.00)", -123456.78): "($123,456.78)",
    ("$#,##0.00_);[빨강]($#,##0.00)", -123456.78): "($123,456.78)",
}

# Extract test cases from expected results
test_cases = list(expected_results.keys())


@pytest.mark.parametrize("number_format,value", test_cases)
def test_apply_format(number_format, value):
    expected_output = expected_results[(number_format, value)]
    actual_output = number.apply_format(value, number_format)

    assert actual_output == expected_output, (
        f"Failed for format '{number_format}' with value {value}: "
        f"expected '{expected_output}', got '{actual_output}'"
    )
